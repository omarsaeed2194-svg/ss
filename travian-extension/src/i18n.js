export const LANGUAGES = [['ar', 'العربية'], ['en', 'English']];

let current = 'ar';

export function setLanguage(lang) {
  current = STRINGS[lang] ? lang : 'ar';
  return current;
}

export const getLanguage = () => current;
export const isRtl = () => current === 'ar';

// Locale for dates and times: Arabic wording with Western digits, matching Travian.
export const dateLocale = () => (current === 'ar' ? 'ar-u-nu-latn' : undefined);

export function t(key, params = {}) {
  const v = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (typeof v === 'function') return v(params);
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
}

// Fill static markup: data-i18n (text), data-i18n-html, data-i18n-title.
export function applyI18n(root = document) {
  document.documentElement.lang = current;
  document.documentElement.dir = isRtl() ? 'rtl' : 'ltr';
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}

// Keep coordinates like (12|-34) left-to-right inside Arabic text.
export const coords = (x, y) => `⁦(${x ?? '?'}|${y ?? '?'})⁩`;
export const ltr = (s) => `⁦${s}⁩`;
